#!/usr/bin/env python3
"""Extract every newly generated mapping and check its original entry bytes."""
import hashlib
import json
from pathlib import Path
import re
import struct

ROOT = Path(__file__).resolve().parents[1]
PORT = ROOT / "ports/game_europe"
BUILD = ROOT / "build/indirect-codegen"
def mappings(folder):
    text = (folder / "carbon_europe_init.cpp").read_text()
    return {int(address,16): name for address,name in re.findall(r"\{ 0x([0-9A-Fa-f]+), (\w+) \}",text)}
baseline = mappings(PORT / "generated")
baseline[0x824DAC58] = "sub_824DAC58"
generated = mappings(BUILD / "generated")
extra = {address:name for address,name in generated.items() if address not in baseline}
requested = {int(item["address"],16) for item in json.loads((PORT / "indirect_entries.json").read_text())["entries"]}
assert requested <= generated.keys(), "SDK must emit every requested target"
bodies = {}
unresolved = set()
for file in (BUILD / "generated").glob("carbon_europe_recomp.*.cpp"):
    for match in re.finditer(r"^DEFINE_REX_FUNC\((\w+)\) \{.*?^\}",file.read_text(),re.M|re.S):
        name = match[1]
        if name in extra.values():
            assert name not in bodies, name
            for source,target in re.findall(r'Unresolved (?:call|branch) from 0x([0-9A-Fa-f]+) to 0x([0-9A-Fa-f]+)',match[0]):
                unresolved.add((int(source,16),int(target,16)))
            bodies[name] = match[0]
assert set(extra.values()) <= bodies.keys(), "All additional mappings must have compiled bodies"
image = (PORT / "image.bin").read_bytes()
parents = {}
if unresolved:
    targets = set()
    for source,target in sorted(unresolved):
        instruction = struct.unpack_from('>I',image,source-0x82000000)[0]
        opcode = instruction >> 26
        assert opcode in (16,18), (hex(source),hex(instruction))
        bits = 16 if opcode == 16 else 26
        displacement = instruction & ((1<<bits)-4)
        if displacement & (1<<(bits-1)):
            displacement -= 1<<bits
        actual = (displacement if instruction & 2 else source+displacement) & 0xFFFFFFFF
        assert actual == target, (hex(source),hex(target),hex(actual))
        assert instruction & 1 == 0, 'Only non-linking tail branches are bridged'
        targets.add(target)
    # A computed-entry body can branch back into a parent block. Preserve the
    # already generated parent's labels and locals, entering after its prologue.
    missing = targets - extra.keys() - baseline.keys()
    for file in (PORT/'generated').glob('carbon_europe_recomp.*.cpp'):
        text = file.read_text()
        hits = {target for target in missing if f'loc_{target:08X}:' in text}
        if not hits:
            continue
        for match in re.finditer(r'^DEFINE_REX_FUNC\((\w+)\) \{.*?^\}',text,re.M|re.S):
            for target in hits:
                if f'loc_{target:08X}:' in match[0]:
                    assert target not in parents, f'Ambiguous generated block {target:08X}'
                    parents[target] = (match[1],match[0])
    assert missing == parents.keys(), 'Every bridge must point to an existing generated label'
    for target,(parent,body) in parents.items():
        name = f'sub_{target:08X}'
        body = body.replace(f'DEFINE_REX_FUNC({parent})',f'DEFINE_REX_FUNC({name})',1)
        first_instruction = body.index('\n\t// ')
        prefix = body[:first_instruction]
        assert 'ctx.' not in prefix, 'Entry must precede guest prologue, after host locals'
        body = prefix + f'\n\tgoto loc_{target:08X};' + body[first_instruction:]
        assert 'REX_FATAL' not in body
        extra[target] = name
        bodies[name] = body
    names = {**baseline,**extra}
    def bridge(match):
        kind,source,target = match.groups()
        target_name = names[int(target,16)]
        if kind == 'call':
            return f'{target_name}(ctx, base);'
        return '{ '+f'{target_name}(ctx, base); return;'+' }'
    for name,body in list(bodies.items()):
        body = re.sub(r'REX_FATAL\("Unresolved (call|branch) from 0x([0-9A-Fa-f]+) to 0x([0-9A-Fa-f]+)"\);',bridge,body)
        body = re.sub(r'^\s*// (?:FATAL: unresolved function|ERROR: conditional branch to unknown address)[^\n]*\n','\n',body,flags=re.M)
        bodies[name] = body
    (BUILD/'verified_branch_targets.json').write_text(json.dumps({
        'targets':[f'0x{address:08X}' for address in sorted(targets)],
        'branches':[{'source':f'0x{source:08X}','target':f'0x{target:08X}'} for source,target in sorted(unresolved)]
    },indent=2)+'\n')
    print(f'Bridged {len(unresolved)} verified tail branches through {len(missing)} original generated block entries')
assert all('REX_FATAL' not in body for body in bodies.values())
lines = ['// Additional indirect entries generated by ReXGlue v0.10.0 from the local Europe XEX.',
         '#include "carbon_europe_init.h"', '#include "supplemental_indirect.h"',
         '#include <array>', '#include <cstdio>', '#include <stdexcept>', '']
for name in sorted(bodies):
    lines.append(f'DECLARE_REX_FUNC({name});')
lines.append('')
lines.extend(bodies[name]+'\n' for _,name in sorted(extra.items()))
lines += ['namespace {', 'struct Entry { uint32_t address; PPCFunc* function; std::array<uint32_t,8> words; };',
          f'const std::array<Entry,{len(extra)}> entries = {{{{']
details = []
for address,name in sorted(extra.items()):
    words = struct.unpack_from('>8I', image, address-0x82000000)
    values = ','.join(f'0x{word:08X}' for word in words)
    lines.append(f'  {{0x{address:08X},{name},{{{values}}}}},')
    details.append({'address':f'0x{address:08X}','symbol':name,
                    'first_words':[f'0x{word:08X}' for word in words],
                    'body_sha256':hashlib.sha256(bodies[name].encode()).hexdigest()})
lines += ['}};', '}',
'''size_t RegisterSupplementalIndirectEntries(rex::runtime::FunctionDispatcher* dispatcher,uint8_t* base){
  size_t added=0;
  for(const auto& entry:entries){
    if(dispatcher->GetFunction(entry.address))continue;
    for(size_t index=0;index<entry.words.size();++index){
      if(REX_LOAD_U32(entry.address+uint32_t(index*4))!=entry.words[index]){
        char message[128];std::snprintf(message,sizeof(message),"XEX mismatch at indirect entry 0x%08X",entry.address);
        throw std::runtime_error(message);
      }
    }
    if(!dispatcher->SetFunction(entry.address,entry.function))
      throw std::runtime_error("Could not register supplemental indirect entry");
    ++added;
  }
  return added;
}''']
(PORT / "supplemental_indirect.cpp").write_text('\n'.join(lines)+'\n')
(PORT / "supplemental_indirect.h").write_text('''#pragma once
#include <cstddef>
#include <cstdint>
#include <rex/system/function_dispatcher.h>
size_t RegisterSupplementalIndirectEntries(rex::runtime::FunctionDispatcher*,uint8_t*);
''')
manifest = {
    'tool':'ReXGlue v0.10.0', 'requested_targets':len(requested),
    'xex_sha256':hashlib.sha256((PORT/'default.xex').read_bytes()).hexdigest(),
    'entries':details,
    'verified_tail_branches':[{'source':f'0x{source:08X}','target':f'0x{target:08X}'} for source,target in sorted(unresolved)],
    'block_entries':{f'0x{target:08X}':parent for target,(parent,_) in sorted(parents.items())},
    'block_entry_method':'Copy unchanged SDK-generated parent body and host locals; goto original entry label before guest prologue. Tail bridges are validated non-linking PPC b/bc instructions.'
}
(PORT / "supplemental_indirect.json").write_text(json.dumps(manifest,indent=2)+'\n')
asset_path = ROOT/'app/src/main/assets/carbon-module.json'
asset = json.loads(asset_path.read_text())
asset['supplemental_indirect_entry_count'] = len(extra)
asset['supplemental_indirect_manifest_sha256'] = hashlib.sha256((PORT/'supplemental_indirect.json').read_bytes()).hexdigest()
asset_path.write_text(json.dumps(asset,indent=2)+'\n')
print(f'Extracted {len(extra)} generated indirect entries ({len(requested)} table targets plus discovered dependencies)')
