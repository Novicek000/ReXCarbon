#!/usr/bin/env python3
"""Extract the verified Europe career callback from a successful SDK codegen."""
import hashlib
import json
from pathlib import Path
import re
import struct

ROOT = Path(__file__).resolve().parents[1]
PORT = ROOT/'ports/game_europe'
BUILD = ROOT/'build/career-codegen'
log = (BUILD/'codegen.log').read_text(errors='replace')
assert 'Codegen summary:' in log and re.search(r'Done in [0-9.]+s\.', log), 'SDK codegen must finish successfully'
image = (PORT/'image.bin').read_bytes()
entry = 0x825BF858
words = [0x7C6B1B78, 0x39200002, 0x3D4082FF, 0x386AA040,
         0x992B0012, 0x39600000, 0x91630014, 0x4BFFF984]
assert list(struct.unpack_from('>8I', image, entry-0x82000000)) == words
# The full callback address is synthesized in executable code, not a data table.
high_pc, low_pc = 0x825BC79C, 0x825BC7AC
assert struct.unpack_from('>5I', image, high_pc-0x82000000) == (
    0x3D60825C, 0x907E0024, 0x7FE5FB78, 0x807F000C, 0x388BF858)
assert ((0x825C0000 + (0xF858-0x10000)) & 0xFFFFFFFF) == entry
displacement = words[-1] & 0x03FFFFFC
if displacement & 0x02000000:
    displacement -= 0x04000000
assert words[-1] >> 26 == 18 and words[-1] & 3 == 0
assert (entry+7*4+displacement) & 0xFFFFFFFF == 0x825BF1F8
baseline = (PORT/'generated/carbon_europe_funcs.h').read_text()
assert 'DECLARE_REX_FUNC(sub_825BF1F8)' in baseline
found = []
for chunk in sorted((BUILD/'generated').glob('carbon_europe_recomp.*.cpp')):
    source = chunk.read_text()
    if 'DEFINE_REX_FUNC(sub_825BF858)' not in source:
        continue
    match = re.search(r'^DEFINE_REX_FUNC\(sub_825BF858\) \{.*?^\}', source, re.M | re.S)
    assert match, chunk
    found.append((chunk.name, match.group(0)))
assert len(found) == 1, f'Expected one SDK-generated callback, got {len(found)}'
chunk, body = found[0]
assert 'sub_825BF1F8(ctx, base);' in body
assert not any(x in body for x in ('REX_FATAL', 'REX_UNIMPLEMENTED', 'Unresolved'))
assert len(re.findall(r'^\s*// ', body, re.M)) == len(words)
header = ('// Supplemental career callback generated by ReXGlue v0.10.0 from the local Europe XEX.\n'
          '#include "carbon_europe_pch.h"\nDECLARE_REX_FUNC(sub_825BF1F8);\n\n')
(PORT/'supplemental_825BF858.cpp').write_text(header+body+'\n')
metadata = {
    'tool': 'ReXGlue v0.10.0', 'entry': f'0x{entry:08X}', 'tail_target': '0x825BF1F8',
    'xex_sha256': hashlib.sha256((PORT/'default.xex').read_bytes()).hexdigest(),
    'codegen_manifest_sha256': hashlib.sha256((BUILD/'carbon_europe.toml').read_bytes()).hexdigest(),
    'original_words': [f'0x{x:08X}' for x in words],
    'address_reference': {'high_at': f'0x{high_pc:08X}', 'low_at': f'0x{low_pc:08X}',
                          'high_word': '0x3D60825C', 'low_word': '0x388BF858'},
    'generated_body_sha256': hashlib.sha256(body.encode()).hexdigest(), 'source_chunk': chunk,
}
(PORT/'supplemental_825BF858.json').write_text(json.dumps(metadata, indent=2)+'\n')
print(f'Extracted {entry:08X} from {chunk}; all 8 original words, pointer reference and tail branch verified')
