#!/usr/bin/env python3
"""Keep the SDK-generated loading entry without rebuilding every unchanged chunk."""
import hashlib
import json
from pathlib import Path
import struct

ROOT = Path(__file__).resolve().parents[1]
PORT = ROOT / "ports/game_europe"
CODEGEN = ROOT / "build/entry-codegen"
WORDS = [0x3D608208, 0x38A00000, 0x388BB714, 0x3D6082C6, 0x806B4ACC, 0x4BE231F4]
image = (PORT / "image.bin").read_bytes()
assert list(struct.unpack_from(">6I", image, 0x824DAC58-0x82000000)) == WORDS
matches = []
for file in (CODEGEN / "generated").glob("carbon_europe_recomp.*.cpp"):
    text = file.read_text()
    marker = "DEFINE_REX_FUNC(sub_824DAC58)"
    if marker in text:
        start = text.index(marker)
        end = text.index("\n}\n", start)+3
        matches.append((file, text[start:end]))
assert len(matches) == 1
file, body = matches[0]
assert "sub_822FDE60(ctx, base);" in body and "REX_FATAL" not in body
source = ('// Supplemental entry generated by ReXGlue v0.10.0 from the local Europe XEX.\n'
          '#include "carbon_europe_pch.h"\nDECLARE_REX_FUNC(sub_822FDE60);\n\n' + body)
(PORT / "supplemental_824DAC58.cpp").write_text(source)
provenance = {
    "tool": "ReXGlue v0.10.0", "entry": "0x824DAC58", "tail_target": "0x822FDE60",
    "xex_sha256": hashlib.sha256((PORT / "default.xex").read_bytes()).hexdigest(),
    "codegen_manifest_sha256": hashlib.sha256((CODEGEN / "carbon_europe.toml").read_bytes()).hexdigest(),
    "original_words": [f"0x{word:08X}" for word in WORDS],
    "generated_body_sha256": hashlib.sha256(body.encode()).hexdigest(),
    "source_chunk": file.name,
}
(PORT / "supplemental_824DAC58.json").write_text(json.dumps(provenance, indent=2)+"\n")
print("Extracted validated SDK-generated entry 0x824DAC58 -> 0x822FDE60")
